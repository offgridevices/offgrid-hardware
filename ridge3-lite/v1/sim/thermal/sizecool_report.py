# -*- coding: utf-8 -*-
"""results-size-cooling.md from out/thermal/sc/res/*.json (see sizecool.py)."""
import glob
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
RES = os.path.join(REPO, 'out', 'thermal', 'sc', 'res')
COOLS = ['none', 'top', 'bottom', 'both', 'fins']
CNAME = dict(none='none (bare)', top='top plate', bottom='bottom plate', both='both plates', fins='finned top sink',
             topF='top plate, full pad', bottomF='bottom plate, full pad', bothF='both plates, full pad',
             finsF='finned top, full pad', finsbot='finned top + bottom plate (extra)')
LIM = dict(FET=150, MCU=105, IMU=85, X5R=85, shunt=170)
KEY = 'full60-50C-wash-sun'


def board_mass(r):
    """FR-4 + copper (planes and pours ~80 % covered), grams."""
    A = r['info']['board_mm2'] * 1e-6
    tcu = [35e-6] * 2 + [70e-6 if r['cu'] == '2' else 35e-6] * 4
    return A * ((1.6e-3 - sum(tcu)) * 1900 + 0.8 * sum(tcu) * 8960) * 1e3


def load():
    R = {}
    for p in glob.glob(os.path.join(RES, '*.json')):
        r = json.load(open(p))
        R[(r['board'], r['cu'], r['cool'])] = r
    return R


def f0(x):
    return '-' if x is None or (isinstance(x, float) and math.isnan(x)) else '%.0f' % x


def cell(c, k, lim=None):
    if c is None or c.get('runaway'):
        return 'runaway'
    x = c.get(k)
    s = f0(x)
    return '**%s**' % s if lim and x is not None and x > lim else s


def main():
    R = load()
    L = ['# Ridge 3 Lite: board size x copper x cooling', '',
         'Generated by `sizecool.py` / `sizecool_report.py` from the placed (unrouted) boards:',
         '`out/r7/placed.kicad_pcb` (35 mm) and `out/m38k/placed.kicad_pcb` (38 mm: FC MCU at the centre,',
         'drivers 4.0 mm from it, GVDD LDO on top).',
         '',
         'Every combination carries variant b\'s copper (`results-placed.md`): GND fill on F, In2, In3 and B',
         'with stitching to In1, and vias in and around the battery pads and on R_S1\'s GND pad.',
         '',
         '- Stackup: 1 oz on all six layers, or 2 oz inner ("cu2").',
         '- Loads per motor: hover 3.5 A, full 15 A (`full60`: 60 s from steady hover).',
         '- Ambient: 50 C with 1000 W/m2 sun, or 25 C shade. Prop wash is the momentum-theory estimate;',
         '  `halfwash` halves every forced h.',
         '- Limits: FET channel 175 C (target 150), ESC MCU Tj 105 C, IMU 85 C, X5R 85 C (105 derated),',
         '  shunt 170 C. Bold is over the limit.',
         '',
         '## Cooling options and their assumptions',
         '',
         '- **Plates:** 1.0 mm 6061-T6 (k 167 W/mK) covering the whole face, black anodised (emissivity 0.85;',
         '  the top one absorbs 0.9 of the sun).',
         '- **Plate cooling:** its outer face is cooled exactly as the board face it covers (prop wash, natural',
         '  convection, radiation). The covered board face loses its own convection.',
         '- **Gap pad (3 W/mK, 3.1 g/cm3), the assumption asked for:**',
         '  - the plate underside sits 1.5 mm off the board, i.e. 1.0 mm parts plus 0.5 mm pad;',
         '  - parts 1.0 mm or taller touch through 0.5 mm of pad (the plate is pocketed over taller parts);',
         '  - lower parts touch through a stepped pad 1.5 mm minus their height thick, so the thinner the part,',
         '    the thicker (and weaker) its pad;',
         '  - contact area is 0.8 x the courtyard box.',
         '- **Heat path into the pad:**',
         '  - parts with a junction model: from the junction through RthJ-top (datasheet RthJC(top) where',
         '    given; TPN2R304PL 15 K/W and STM32 25-30 K/W assumed);',
         '  - other parts: from their pads through the body (k 3 for MLCC, 5 for resistors, 4 for inductors,',
         '    0.8-1 for moulded parts).',
         '- **Bare board (between parts):** joined to the plate across the 1.5 mm air gap only (air 0.028 W/mK',
         '  plus 8 W/m2K radiation).',
         '- **Full-pad bound** (pad also filling the bare board, `topF` etc. in `sizecool.py`): defined but not run in this study.',
         '- **"finned top + bottom plate (extra)":** not in the brief; added because fins and the bottom plate',
         '  were the two options that helped.',
         '- **Finned top sink:** the top plate plus 4 mm fins, 0.5 mm thick at 1.5 mm pitch. Convection on it is',
         '  the plate\'s h x (exposed base + fin efficiency 0.98 x fin area) / base = 6.2 x. That assumes the wash',
         '  reaches the channels at the speed it has over a flat plate, which is optimistic.',
         '- **Masses** are plate (+ fins) + pad. Board masses (FR-4 + copper) are listed for the size comparison.',
         '']
    # masses
    MC = COOLS + ['finsbot']
    L += ['## Masses (g)', '', 'Board = FR-4 + copper (planes and pours about 80 % covered). Cooling = plate(s) + fins + pad.', '',
          '| board | copper | board | ' + ' | '.join(CNAME[c] for c in MC) + ' |',
          '|---|---|---|' + '---|' * len(MC)]
    for b in ('35', '38'):
        for cu in ('1', '2'):
            r0 = R.get((b, cu, 'none'))
            if not r0:
                continue
            row = ['%.1f' % sum(R[(b, cu, c)]['info']['mass_g'].values()) if (b, cu, c) in R else '-' for c in MC]
            L.append('| %s mm | %s | %.1f | %s |' % (b, '1 oz' if cu == '1' else '2 oz inner', board_mass(r0), ' | '.join(row)))
    # key table
    L += ['', '## Full throttle for 60 s, 50 C, sun, prop wash (the design case)', '',
          'AM32 cap = the sustained current fraction (all four motors alike, steady state) at which the hottest',
          'ESC MCU sits at 100 C, at 50 C in the sun. 1.00 means the cap never bites at full throttle.', '',
          '| board | copper | cooling | cooling g | FET | ESC MCU | IMU | X5R | shunt | battery pad | board max | AM32 cap wash | AM32 cap halfwash |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    cands = []
    for b in ('35', '38'):
        for cu in ('1', '2'):
            for c in COOLS + ['finsbot'] + [x + 'F' for x in COOLS[1:]]:
                r = R.get((b, cu, c))
                if not r or KEY not in r['cases']:
                    continue
                k = r['cases'][KEY]
                mass = sum(r['info']['mass_g'].values())
                dw, dh = r.get('derate_wash', {}), r.get('derate_halfwash', {})
                L.append('| %s mm | %s | %s | %.1f | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
                    b, '1 oz' if cu == '1' else '2 oz in', CNAME[c], mass, cell(k, 'FET', 150), cell(k, 'MCU', 105),
                    cell(k, 'IMU', 85), cell(k, 'X5R', 85), cell(k, 'shunt', 170), f0(k.get('batpad')), f0(k.get('board')),
                    '%.2f' % dw['k'] if dw else '-', '%.2f' % dh['k'] if dh else '-'))
                if not k.get('runaway'):
                    over = max(k['FET'] - 150, k['MCU'] - 105, k['IMU'] - 85)
                    cands.append(dict(b=b, cu=cu, c=c, over=over, total=mass + board_mass(r), cool=mass,
                                      full=(dw.get('k', 0) >= 0.999), k=k, dw=dw))
    # other cases
    others = ['hover-50C-wash-sun', 'hover-25C-wash-shade', 'full60-25C-wash-shade', 'full60-50C-halfwash-sun',
              'punch-50C-wash-sun', 'abuse2-50C-wash-sun', 'abuse2-25C-wash-shade']
    L += ['', '## Other cases: FET / ESC MCU / IMU, C', '',
          '- `punch`: 8 x (10 s hover + 3 s full).',
          '- `abuse2`: from steady cruise, motor 1 stalled at 25 A for 2 s, the others at hover.', '',
          '| board | copper | cooling | ' + ' | '.join(others) + ' |', '|---|---|---|' + '---|' * len(others)]
    for b in ('35', '38'):
        for cu in ('1', '2'):
            for c in COOLS + ['finsbot'] + [x + 'F' for x in COOLS[1:]]:
                r = R.get((b, cu, c))
                if not r:
                    continue
                cs = []
                for o in others:
                    k = r['cases'].get(o)
                    cs.append('-' if k is None else ('runaway' if k.get('runaway') else '%s / %s / %s' % (
                        cell(k, 'FET', 150), cell(k, 'MCU', 105), cell(k, 'IMU', 85))))
                L.append('| %s mm | %s | %s | %s |' % (b, '1 oz' if cu == '1' else '2 oz in', CNAME[c], ' | '.join(cs)))
    # 35 vs 38
    L += ['', '## 35 mm against 38 mm (full60, 50 C, sun, wash)', '',
          '| copper | cooling | FET 35 / 38 | ESC MCU 35 / 38 | IMU 35 / 38 | AM32 cap wash 35 / 38 | AM32 cap halfwash 35 / 38 | board + cooling g, 35 / 38 |',
          '|---|---|---|---|---|---|---|---|']
    for cu in ('1', '2'):
        for c in COOLS + ['finsbot']:
            a, b_ = R.get(('35', cu, c)), R.get(('38', cu, c))
            if not a or not b_ or KEY not in a['cases'] or KEY not in b_['cases']:
                continue
            ka, kb = a['cases'][KEY], b_['cases'][KEY]
            pair = lambda key: '%s / %s' % (cell(ka, key), cell(kb, key))
            cap = lambda r, air: '%.2f' % r['derate_' + air]['k'] if 'derate_' + air in r else '-'
            L.append('| %s | %s | %s | %s | %s | %s / %s | %s / %s | %.1f / %.1f |' % (
                '1 oz' if cu == '1' else '2 oz in', CNAME[c], pair('FET'), pair('MCU'), pair('IMU'),
                cap(a, 'wash'), cap(b_, 'wash'), cap(a, 'halfwash'), cap(b_, 'halfwash'),
                board_mass(a) + sum(a['info']['mass_g'].values()), board_mass(b_) + sum(b_['info']['mass_g'].values())))
    # recommendation
    L += ['', '## Recommendation', '']
    ok = [x for x in cands if x['over'] <= 0 and x['full']]
    if ok:
        best = min(ok, key=lambda x: x['total'])
        L.append('Lightest combination that meets FET < 150, MCU < 105 and IMU < 85 at full60, 50 C sun, prop wash, '
                 'with the AM32 cap not biting: **%s mm, %s, %s**, %.1f g of cooling (%.1f g with the board).' % (
                     best['b'], '1 oz' if best['cu'] == '1' else '2 oz inner', CNAME[best['c']], best['cool'], best['total']))
    else:
        close = sorted(cands, key=lambda x: x['over'])[:5]
        L.append('No combination meets all three limits (FET < 150, MCU < 105, IMU < 85) at full60, 50 C sun, prop wash.')
        L.append('')
        L.append('Closest, ranked by the worst excess over the three limits:')
        L.append('')
        L.append('| # | board | copper | cooling | board + cooling g | FET | MCU | IMU | worst excess K | AM32 cap wash | AM32 cap halfwash |')
        L.append('|---|---|---|---|---|---|---|---|---|---|---|')
        for i, x in enumerate(close):
            r = R[(x['b'], x['cu'], x['c'])]
            dh = r.get('derate_halfwash', {})
            L.append('| %d | %s mm | %s | %s | %.1f | %.0f | %.0f | %.0f | %.0f | %s | %s |' % (
                i + 1, x['b'], '1 oz' if x['cu'] == '1' else '2 oz inner', CNAME[x['c']], x['total'], x['k']['FET'],
                x['k']['MCU'], x['k']['IMU'], x['over'], '%.2f' % x['dw']['k'] if x['dw'] else '-',
                '%.2f' % dh['k'] if dh else '-'))
    top3 = sorted(cands, key=lambda x: x['over'])[:3]
    L += ['', '## Hover, 50 C, sun, h halved, for the top 3', '',
          '| board | copper | cooling | FET | ESC MCU | IMU | X5R | shunt | board max |', '|---|---|---|---|---|---|---|---|---|']
    for x in top3:
        k = R[(x['b'], x['cu'], x['c'])]['cases'].get('hover-50C-halfwash-sun')
        L.append('| %s mm | %s | %s | %s |' % (x['b'], '1 oz' if x['cu'] == '1' else '2 oz inner', CNAME[x['c']],
                                              ' | '.join(cell(k, q, LIM.get(q)) for q in ('FET', 'MCU', 'IMU', 'X5R', 'shunt', 'board'))
                                              if k else 'not run yet'))
    mark = '<!-- hand-written notes below: kept when this file is regenerated -->'
    path = os.path.join(HERE, 'results-size-cooling.md')
    notes = ''
    if os.path.exists(path) and mark in open(path).read():
        notes = open(path).read().split(mark, 1)[1]
    open(path, 'w').write('\n'.join(L) + '\n\n' + mark + notes)
    print('wrote', path)


if __name__ == '__main__':
    main()
