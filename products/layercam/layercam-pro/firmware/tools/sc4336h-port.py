#!/usr/bin/env python3
"""Make the SC4336H driver for the Luckfox SDK's kernel: a port of its sc4336.c.

    python3 tools/sc4336h-port.py SDK/sysdrv/source/kernel [--chip-id 0xNNNN]

No SC4336H driver exists (not in the Luckfox SDK, nor Rockchip's develop-5.10
and develop-6.1 kernels), and SmartSens keeps the SC4336H's chip ID and
register table under NDA.  SmartSens says the SC4336H is pin-to-pin with the
SC4336, and the family shares the power sequence, the 24 MHz clock, the ID
registers (0x3107/0x3108) and the 2560x1440 2-lane mode.  So this copies
drivers/media/i2c/sc4336.c to sc4336h.c with every name changed (compatible
"smartsens,sc4336h", driver and sensor name "sc4336h", which also names the
IQ file rkaiq loads), and adds VIDEO_SC4336H to the Kconfig and the
Makefile.  Nothing else in the C is changed: no register value is made up.

Without --chip-id the copy's CHIP_ID is 0x10000, which no 16-bit read can
match: the driver powers the sensor up, reads 0x3107/0x3108, logs
"Unexpected sensor id(00xxxx), ret(0)" and gives up.  That log line is the
first chip ID read on a new board (README.md, Bringing up a board).  Run
this again with --chip-id set to what it read and the driver binds.

What stays the SC4336's until SmartSens' table is in hand (TODO(SC4336H)):
the init register list and the mode's timing (VTS/HTS, link frequency),
gain and exposure limits.  A picture from it proves the wiring, not the
tuning.  Standard library only; running it twice gives the same result.
"""
import argparse, os, re, sys

UNKNOWN_ID = '0x10000'
HEADER = """/*
 * GENERATED by LayerCam Pro's firmware/tools/sc4336h-port.py from the SDK's
 * sc4336.c: every name changed, nothing else.  TODO(SC4336H): the register
 * table, the mode timing and the gain/exposure limits below are the
 * SC4336's; the SC4336H's are under SmartSens NDA.
 * CHIP_ID: %s.
 */
"""
KCONFIG = """config VIDEO_SC4336H
	tristate "SmartSens SC4336H sensor support (port of sc4336.c, LayerCam Pro)"
	depends on I2C && VIDEO_V4L2
	select MEDIA_CONTROLLER
	select VIDEO_V4L2_SUBDEV_API
	select V4L2_FWNODE
	help
	  This is a Video4Linux2 sensor driver for the SmartSens
	  SC4336H camera, made from the SC4336 driver.

"""
MAKEFILE = 'obj-$(CONFIG_VIDEO_SC4336H) += sc4336h.o\n'


class PortError(Exception):
    pass


def port_source(src, chip_id=None):
    """sc4336.c's text -> sc4336h.c's text."""
    for anchor in (r'^#define CHIP_ID\s+0x[0-9a-fA-F]+\s*$', r'^#define SC4336_REG_CHIP_ID\s+0x3107\s*$',
                   r'\{ \.compatible = "smartsens,sc4336" \}', r'^#define SC4336_NAME\s+"sc4336"\s*$'):
        if len(re.findall(anchor, src, re.M)) != 1:
            raise PortError('sc4336.c is not the one this was written for (no single %r)' % anchor)
    if re.search(r'sc4336h', src, re.I):
        raise PortError('the source already mentions sc4336h: give the SDK\'s own sc4336.c')
    out = re.sub(r'sc4336(?![hp])', 'sc4336h', src)
    out = re.sub(r'SC4336(?![HP])', 'SC4336H', out)
    if chip_id is None:
        value, note = UNKNOWN_ID, 'unknown (no 16-bit read matches: probe logs the ID it read)'
    else:
        value, note = '0x%04x' % chip_id, '0x%04x, read from a board' % chip_id
    out = re.sub(r'^(#define CHIP_ID\s+)0x[0-9a-fA-F]+(\s*)$', lambda m: m.group(1) + value + m.group(2), out,
                 count=1, flags=re.M)
    lines = out.split('\n', 1)
    if lines[0].startswith('// SPDX'):
        return lines[0] + '\n' + HEADER % note + lines[1]
    return HEADER % note + out


def add_kconfig(text):
    if 'config VIDEO_SC4336H\n' in text:
        return text
    i = text.find('config VIDEO_SC4336\n')
    if i < 0:
        raise PortError('no VIDEO_SC4336 entry in drivers/media/i2c/Kconfig')
    return text[:i] + KCONFIG + text[i:]


def add_makefile(text):
    if MAKEFILE in text:
        return text
    m = re.search(r'^obj-\$\(CONFIG_VIDEO_SC4336\) \+= sc4336\.o\n', text, re.M)
    if not m:
        raise PortError('no sc4336.o line in drivers/media/i2c/Makefile')
    return text[:m.end()] + MAKEFILE + text[m.end():]


def port(kernel_dir, chip_id=None):
    d = os.path.join(kernel_dir, 'drivers', 'media', 'i2c')
    paths = {n: os.path.join(d, n) for n in ('sc4336.c', 'Kconfig', 'Makefile')}
    texts = {}
    for n, p in paths.items():
        try:
            with open(p) as f:
                texts[n] = f.read()
        except OSError as e:
            raise PortError('%s: %s' % (p, e.strerror))
    new = {os.path.join(d, 'sc4336h.c'): port_source(texts['sc4336.c'], chip_id),
           paths['Kconfig']: add_kconfig(texts['Kconfig']),
           paths['Makefile']: add_makefile(texts['Makefile'])}
    for p, t in new.items():
        with open(p, 'w') as f:
            f.write(t)
    return sorted(new)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('kernel_dir', help='the SDK kernel: sysdrv/source/kernel')
    ap.add_argument('--chip-id', type=lambda v: int(v, 0), help='the SC4336H chip ID read from a board (0x3107/0x3108)')
    a = ap.parse_args(argv)
    if a.chip_id is not None and not 0 <= a.chip_id <= 0xffff:
        print('sc4336h-port: the chip ID is 16 bits', file=sys.stderr)
        return 2
    try:
        for p in port(a.kernel_dir, a.chip_id):
            print('wrote %s' % p)
    except PortError as e:
        print('sc4336h-port: %s' % e, file=sys.stderr)
        return 1
    if a.chip_id is None:
        print('note: chip ID unknown: the driver will log the ID it reads and not bind (README.md)')
    print('TODO(SC4336H): the register table is still the SC4336\'s')
    return 0


if __name__ == '__main__':
    sys.exit(main())
